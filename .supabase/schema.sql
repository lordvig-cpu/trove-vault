-- 2. REUSABLE SYSTEM AUDIT TRIGGER FUNCTION
CREATE OR REPLACE FUNCTION update_sys_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
   NEW.sys_updated_at = NOW();
   RETURN NEW;
END;
$$ LANGUAGE 'plpgsql';

-- 3. COLLECTIONS TABLE (Curated Playlists & Grouping Containers)
CREATE TABLE IF NOT EXISTS collections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT REFERENCES collections(id) ON DELETE CASCADE,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  icon VARCHAR(20) DEFAULT '📁',
  sys_active BOOLEAN DEFAULT true,
  sys_created_by UUID,
  sys_updated_by UUID,
  sys_created_at TIMESTAMPTZ DEFAULT NOW(),
  sys_updated_at TIMESTAMPTZ DEFAULT NOW()
);

DROP TRIGGER IF EXISTS tr_collections_updated_at ON collections;
CREATE TRIGGER tr_collections_updated_at
  BEFORE UPDATE ON collections
  FOR EACH ROW
  EXECUTE FUNCTION update_sys_updated_at_column();

-- 4. MASTER ITEM TEMPLATES (Item Type Blueprints)
CREATE TABLE IF NOT EXISTS item_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID, -- Links to auth.users for personal template forks
  name VARCHAR(100) NOT NULL,
  description TEXT,
  icon VARCHAR(50) DEFAULT '📦',
  is_system_preset BOOLEAN NOT NULL DEFAULT true,
  sys_created_at TIMESTAMPTZ DEFAULT NOW(),
  sys_updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(name, user_id)
);

DROP TRIGGER IF EXISTS tr_item_templates_updated_at ON item_templates;
CREATE TRIGGER tr_item_templates_updated_at
  BEFORE UPDATE ON item_templates
  FOR EACH ROW
  EXECUTE FUNCTION update_sys_updated_at_column();

-- 5. ITEM TEMPLATE FIELDS (Dynamic Schema Attributes per Template)
CREATE TABLE IF NOT EXISTS item_template_fields (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES item_templates(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  label VARCHAR(100) NOT NULL,
  field_type VARCHAR(50) NOT NULL DEFAULT 'text',
  options JSONB DEFAULT '[]'::jsonb,
  is_required BOOLEAN NOT NULL DEFAULT false,
  display_order INT NOT NULL DEFAULT 0,
  sys_created_at TIMESTAMPTZ DEFAULT NOW(),
  sys_updated_at TIMESTAMPTZ DEFAULT NOW()
);

DROP TRIGGER IF EXISTS tr_item_template_fields_updated_at ON item_template_fields;
CREATE TRIGGER tr_item_template_fields_updated_at
  BEFORE UPDATE ON item_template_fields
  FOR EACH ROW
  EXECUTE FUNCTION update_sys_updated_at_column();

-- 6. ITEMS TABLE (Decoupled & Item-Centric)
CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT REFERENCES item_templates(id) ON DELETE SET NULL,
  parent_id BIGINT REFERENCES items(id) ON DELETE CASCADE,
  name VARCHAR(255) NOT NULL,
  attributes JSONB DEFAULT '{}'::jsonb,
  sys_active BOOLEAN DEFAULT true,
  sys_created_by UUID,
  sys_updated_by UUID,
  sys_created_at TIMESTAMPTZ DEFAULT NOW(),
  sys_updated_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

DROP TRIGGER IF EXISTS tr_items_updated_at ON items;
CREATE TRIGGER tr_items_updated_at
  BEFORE UPDATE ON items
  FOR EACH ROW
  EXECUTE FUNCTION update_sys_updated_at_column();

-- 7. ITEM COLLECTIONS (Many-to-Many Junction Table)
CREATE TABLE IF NOT EXISTS item_collections (
  item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  collection_id BIGINT NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
  sys_created_by UUID,
  sys_created_at TIMESTAMPTZ DEFAULT NOW(),
  PRIMARY KEY (item_id, collection_id)
);

-- Indexes for tree traversal, foreign key lookups, and JSONB search performance
CREATE INDEX IF NOT EXISTS idx_items_parent_id ON items(parent_id);
CREATE INDEX IF NOT EXISTS idx_items_template_id ON items(template_id);
CREATE INDEX IF NOT EXISTS idx_items_attributes_gin ON items USING GIN (attributes);
CREATE INDEX IF NOT EXISTS idx_item_template_fields_template_id ON item_template_fields(template_id);
CREATE INDEX IF NOT EXISTS idx_item_collections_collection_id ON item_collections(collection_id);
CREATE INDEX IF NOT EXISTS idx_item_collections_item_id ON item_collections(item_id);

